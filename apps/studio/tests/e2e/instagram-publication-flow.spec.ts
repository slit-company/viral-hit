import { test, expect } from '@playwright/test';
import { readFile, mkdir } from 'node:fs/promises';
import { createDemoMedia } from '../../scripts/demo-media.mjs';
const headers = { 'x-viral-hit-workspace-request': '1' };

test('Instagram draft selects a destination, plays retained media, revises to Story and approves the exact revision', async ({ page, request }) => {
  await page.route('https://www.facebook.com/**', route => route.fulfill({ contentType: 'text/html', body: '<h1>Meta consent fixture</h1>' }));
  await page.goto('/connections'); await page.getByRole('button', { name: 'Connect Instagram', exact: true }).click();
  await expect(page).toHaveURL(/^https:\/\/www.facebook.com\//);
  const state = new URL(page.url()).searchParams.get('state')!;
  await page.goto(`http://127.0.0.1:3042/api/app/publishing/instagram/callback?state=${state}&code=fixture-code`);
  await page.getByLabel('Page and Instagram account', { exact: true }).selectOption('112');
  await page.getByRole('button', { name: 'Connect this account', exact: true }).click();
  await expect(page).toHaveURL('http://127.0.0.1:3042/connections');
  const accounts = await (await request.get('/api/app/publishing/instagram/accounts', { headers })).json();
  const account = accounts.accounts.find((value: { instagramId: string; status: string }) => value.instagramId === '223' && value.status === 'connected'); expect(account).toBeTruthy();
  await mkdir('test-results', { recursive: true }); createDemoMedia('test-results/instagram-publication-source.mp4');
  const created = await request.post('/api/app/projects', { headers, data: { name: 'Field Notes · Instagram release' } }); expect(created.ok()).toBe(true);
  const { id } = await created.json();
  const uploaded = await request.post(`/api/app/projects/${id}/assets`, { headers, multipart: { file: { name: 'light-and-motion.mp4', mimeType: 'video/mp4', buffer: await readFile('test-results/instagram-publication-source.mp4') } } }); expect(uploaded.ok()).toBe(true);
  const asset = (await uploaded.json()).asset;
  await page.setViewportSize({ width: 1440, height: 1000 }); await page.goto(`/publish/${id}`);
  await page.getByRole('combobox', { name: 'Destination', exact: true }).selectOption('instagram');
  await page.getByRole('combobox', { name: 'Instagram account', exact: true }).selectOption(account.id);
  await page.getByRole('combobox', { name: 'Project video', exact: true }).selectOption(asset.id);
  await page.getByRole('combobox', { name: 'AI-generated content?', exact: true }).selectOption('true');
  await page.getByRole('textbox', { name: 'Caption', exact: true }).fill('A quiet study of color and movement.\nMade in Viral Hit.');
  await page.getByRole('button', { name: 'Save draft', exact: true }).click();
  let card = page.getByRole('article', { name: 'Publication Instagram Reel', exact: true });
  await expect(card.getByText('Draft', { exact: true })).toBeVisible();
  await expect(page.getByRole('combobox', { name: 'Destination', exact: true })).toHaveValue('instagram');
  await expect(card.getByRole('button', { name: 'Approve & publish', exact: true })).toBeDisabled();
  await card.locator('video').evaluate(async (video: HTMLVideoElement) => { video.muted = true; await video.play(); });
  await expect.poll(() => card.locator('video').evaluate((video: HTMLVideoElement) => video.currentTime)).toBeGreaterThan(0.5);
  await card.locator('video').evaluate((video: HTMLVideoElement) => video.pause());
  await page.screenshot({ path: 'test-results/instagram-publication-desktop.png' });
  const endpoint = `/api/app/projects/${id}/publications`, draft = (await (await request.get(endpoint, { headers })).json()).publications[0];
  expect(draft.instagramMetadata.kind).toBe('reel'); expect(draft.destinationId).toBe('223');
  await card.getByRole('button', { name: 'Edit draft', exact: true }).click();
  await page.getByRole('combobox', { name: 'Instagram format', exact: true }).selectOption('story');
  await expect(page.getByRole('textbox', { name: 'Caption', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Save new revision', exact: true }).click();
  card = page.getByRole('article', { name: 'Publication Instagram Story', exact: true });
  await expect(card).toBeVisible();
  expect((await request.post(endpoint, { headers, data: { action: 'approve', publicationId: draft.id, expectedRevision: 2, expectedDigest: draft.digest, confirmed: true } })).status()).toBe(409);
  await page.setViewportSize({ width: 390, height: 844 });
  await card.locator('video').evaluate(async (video: HTMLVideoElement) => { video.muted = true; await video.play(); });
  await expect.poll(() => card.locator('video').evaluate((video: HTMLVideoElement) => video.currentTime)).toBeGreaterThan(0.5);
  await card.locator('video').evaluate((video: HTMLVideoElement) => video.pause());
  await card.getByRole('checkbox').check();
  await expect(card.getByRole('button', { name: 'Approve & publish', exact: true })).toBeEnabled();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await card.evaluate(node => node.scrollIntoView({ block: 'start' }));
  await card.getByRole('button', { name: 'Approve & publish', exact: true }).evaluate(async node => { await Promise.all(node.getAnimations().map(animation => animation.finished)); });
  await page.screenshot({ path: 'test-results/instagram-publication-mobile.png' });
  await card.getByRole('button', { name: 'Approve & publish', exact: true }).click();
  await expect(card.getByText('Queued for upload', { exact: true })).toBeVisible();
  await page.reload(); await expect(card.getByText('Queued for upload', { exact: true })).toBeVisible();
  const stored = (await (await request.get(endpoint, { headers })).json()).publications[0];
  expect(stored.state).toBe('approved'); expect(stored.instagramMetadata).toEqual({ kind: 'story', isAiGenerated: true }); expect(stored.instagramDelivery).toBeNull();
  // No publication worker runs in E2E; this is real admission/UI with isolated consent responses.
  await card.getByRole('button', { name: 'Cancel delivery', exact: true }).click(); await expect(card.getByText('Canceled', { exact: true })).toBeVisible();
});
