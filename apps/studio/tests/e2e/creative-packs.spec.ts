  await form.getByLabel('Pack ID', { exact: true }).fill('sunny-kit');
  await form.getByLabel('Author', { exact: true }).fill('Community studio');
  await form.getByLabel('Description', { exact: true }).fill('Plan a consistent host and prepare editable explainer frames.');
  await form.getByLabel('Scope', { exact: true }).selectOption('specialized');
  await form.getByLabel('Use case', { exact: true }).fill('explainers');
  await form.getByRole('checkbox', { name: 'Open frame (open-frame)', exact: true }).check();
  await form.getByRole('checkbox', { name: 'Consistent characters (consistent-characters)', exact: true }).check();
  await form.getByRole('checkbox', { name: 'Sunny host (pack-host)', exact: true }).check();
  const evidence = '../../research/evidence/creative-packs'; await mkdir(evidence, { recursive: true });
  await form.getByRole('button', { name: 'Download creative pack', exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: evidence + '/builder-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await form.getByRole('button', { name: 'Download creative pack', exact: true }).scrollIntoViewIfNeeded();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: evidence + '/builder-mobile.png' });
  await page.setViewportSize({ width: 1440, height: 960 });
  const [download] = await Promise.all([page.waitForEvent('download'), form.getByRole('button', { name: 'Download creative pack', exact: true }).click()]);
  expect(download.suggestedFilename()).toBe('sunny-kit.viralhit-pack.tar');
  const path = resolve('test-results/sunny-kit.viralhit-pack.tar'); await download.saveAs(path);
  const inspected = await mcp(request, { action: 'inspect', path });
  expect(inspected.pack.skillCount).toBe(1); expect(inspected.characters[0].manifest.references[0].sha256).toBe(character.references[0].sha256);
  await page.getByLabel('Import creative pack file', { exact: true }).setInputFiles(path);
  const review = page.getByRole('region', { name: 'Creative pack review' });
  await expect(review.getByRole('heading', { name: 'Sunny explainer kit' })).toBeVisible();
  await review.locator('summary').filter({ hasText: 'Consistent characters' }).click();
  await expect(review.locator('pre')).toContainText('character');
  await expect(review.getByRole('img', { name: 'Sunny host · canonical' })).toBeVisible();
  await expect.poll(() => review.getByRole('img').evaluate(image => (image as HTMLImageElement).naturalWidth)).toBe(320);
  await expect(review.getByRole('button', { name: 'Install creative pack', exact: true })).toBeDisabled();
  await review.locator('summary').filter({ hasText: 'Consistent characters' }).click();
  await review.getByRole('checkbox').scrollIntoViewIfNeeded();
  await page.screenshot({ path: evidence + '/desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await review.getByRole('checkbox').scrollIntoViewIfNeeded();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: evidence + '/mobile.png' });
  await review.getByRole('checkbox').check();
  await review.getByRole('button', { name: 'Install creative pack', exact: true }).click();
