import { test, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import { seededProject } from './seeded-project';

test('review actual visual cuts, seek a selected scene, attach editable ranges and queue customized analysis', async ({ page, request }) => {
  const id = await seededProject('Detected scenes E2E fixture');
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(`/editor/${id}`);
  await page.getByRole('button', { name: 'Generation runs', exact: true }).click();
  await page.getByRole('combobox', { name: 'Creative recipe' }).selectOption('detect-video-scenes');
  const section = page.getByRole('region', { name: 'Detected visual scenes', exact: true });
  await expect(section).toContainText('3 editable scenes · 3.00s');
  await expect(page.getByText('Scenes ready', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Add to timeline', exact: true })).toHaveCount(0);
  await section.getByRole('button', { name: 'Preview scene 2', exact: true }).click();
  const video = section.locator('video');
  await expect.poll(() => video.evaluate((element: HTMLVideoElement) => element.currentTime)).toBe(1);
  await expect(section).toContainText('Selected range: 1.000–2.000 seconds');
  await expect(section.getByRole('button', { name: 'Preview scene 2', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await video.evaluate((element: HTMLVideoElement) => { element.muted = true; return element.play(); });
  await expect.poll(() => video.evaluate((element: HTMLVideoElement) => element.paused)).toBe(true);
  expect(await video.evaluate((element: HTMLVideoElement) => element.currentTime)).toBeLessThan(2.5);
  await section.getByRole('button', { name: 'Preview scene 1', exact: true }).click();
  await expect.poll(() => video.evaluate((element: HTMLVideoElement) => element.currentTime)).toBe(0);
  await expect.poll(() => video.evaluate((element: HTMLVideoElement) => !element.seeking && element.readyState >= 2)).toBe(true);
  const evidence = '../../research/evidence/scenes'; await mkdir(evidence, { recursive: true });
  await section.scrollIntoViewIfNeeded();
  await page.mouse.move(5, 5);
  await page.screenshot({ path: evidence + '/desktop-final-source.png', animations: 'disabled' });
  await page.setViewportSize({ width: 390, height: 844 });
  await section.scrollIntoViewIfNeeded();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: evidence + '/mobile-final-source.png' });
  const attached = page.waitForResponse(response => response.url().endsWith(`/projects/${id}/runs`) && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Add editable sequence', exact: true }).click();
  expect((await (await attached).json()).ok).toBe(true);
  const state = await (await request.get(`/api/app/projects/${id}/timeline`)).json();
  const clips = state.timeline.document.tracks.flatMap((track: { clips: { inPoint: number; outPoint: number; startTime: number }[] }) => track.clips);
  expect(clips.map((clip: { inPoint: number; outPoint: number; startTime: number }) => [clip.inPoint, clip.outPoint, clip.startTime])).toEqual([[0, 1, 0], [1, 2, 1], [2, 3, 2]]);
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  await page.reload();
  const restored = await (await request.get(`/api/app/projects/${id}/timeline`)).json();
  expect(restored.timeline).toEqual(state.timeline);

  await page.setViewportSize({ width: 1440, height: 960 });
  await page.getByRole('button', { name: 'Generation runs', exact: true }).click();
  await page.getByRole('combobox', { name: 'Creative recipe' }).selectOption('detect-video-scenes');
  const assets = (await (await request.get(`/api/app/projects/${id}/assets`)).json()).assets;
  await page.getByLabel('Source video', { exact: true }).selectOption(assets[0].id);
  await page.getByLabel('Visual change threshold', { exact: true }).fill('14');
  await page.getByLabel('Minimum scene length (seconds)', { exact: true }).fill('0.75');
  await page.getByLabel('Maximum scenes', { exact: true }).fill('8');
  const queued = page.waitForResponse(response => response.url().endsWith(`/projects/${id}/runs`) && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Queue workflow', exact: true }).click();
  const response = await queued; expect(response.ok()).toBe(true);
  const runs = (await (await request.get(`/api/app/projects/${id}/runs`)).json()).runs;
  expect(runs).toHaveLength(2);
  const job = runs.flatMap((run: { jobs: { operation: string; state: string; input_json: string }[] }) => run.jobs).find((job: { operation: string; state: string }) => job.operation === 'reference.scenes' && job.state === 'queued');
  expect(JSON.parse(job.input_json)).toMatchObject({ threshold: 14, minDuration: .75, maxScenes: 8, assetId: assets[0].id, pin: { assetId: assets[0].id } });
  expect(errors).toEqual([]);
});
