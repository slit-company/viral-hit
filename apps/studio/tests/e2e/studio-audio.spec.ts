import { test, expect } from '@playwright/test';
import { mkdir, readFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';

const headers = { 'x-viral-hit-workspace-request': '1' };
const evidence = '../../research/evidence/audio-providers';
test('Studio uses an independent audio model, restores options and plays/downloads actual retained WAV output', async ({ page, request }) => {
  await mkdir(evidence, { recursive: true });
  const projectId = (await (await request.post('/api/app/projects', { headers, data: { name: 'Independent audio studio' } })).json()).id;
  const errors: string[] = [], requests: Array<{ mode: string; parameters: Record<string, unknown> }> = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', req => { if (req.url().endsWith('/api/effects/generate')) requests.push(req.postDataJSON().generation); });
  await page.goto('/studio/' + projectId + '?target=audio&model=procedural-sound');
  await expect(page.getByLabel('Audio model', { exact: true })).toHaveValue('procedural-sound');
  await page.getByLabel('Audio prompt', { exact: true }).fill('A short triangular calibration sound');
  await page.getByRole('button', { name: 'Model options', exact: true }).click();
  await page.getByLabel('Frequency (Hz)', { exact: true }).fill('550');
  await page.getByLabel('Length (seconds)', { exact: true }).fill('1.25');
  await page.getByLabel('Wave shape', { exact: true }).selectOption('triangle');
  await page.screenshot({ path: evidence + '/options-desktop.png', animations: 'disabled' });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('button', { name: 'Apply options', exact: true })).toBeInViewport();
  await page.screenshot({ path: evidence + '/options-mobile.png', animations: 'disabled' });
  await page.getByRole('button', { name: 'Apply options', exact: true }).click();
  await page.reload();
  await expect(page.getByLabel('Audio prompt', { exact: true })).toHaveValue('A short triangular calibration sound');
  await page.getByRole('button', { name: 'Model options', exact: true }).click();
  await expect(page.getByLabel('Length (seconds)', { exact: true })).toHaveValue('1.25');
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Media type', exact: true }).click();
  await page.getByRole('option', { name: 'Image', exact: true }).click();
  await page.getByRole('button', { name: 'Media type', exact: true }).click();
  await page.getByRole('option', { name: 'Audio', exact: true }).click();
  await expect(page.getByLabel('Audio prompt', { exact: true })).toHaveValue('A short triangular calibration sound');
  await expect(page.getByRole('button', { name: 'Generate audio', exact: true })).toBeInViewport();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: evidence + '/composer-mobile.png', animations: 'disabled' });
  await page.getByRole('button', { name: 'Generate audio', exact: true }).click();
  await expect(page.getByText('Listen to generated audio', { exact: true })).toBeVisible();
  await page.getByText('Listen to generated audio', { exact: true }).click();
  await expect(page.getByRole('dialog').getByText('Audio', { exact: true })).toBeVisible();
  const audio = page.getByLabel('Generated audio', { exact: true });
  await expect.poll(() => audio.evaluate((el: HTMLAudioElement) => el.readyState)).toBeGreaterThanOrEqual(2);
  expect(await audio.evaluate((el: HTMLAudioElement) => el.duration)).toBeCloseTo(1.25, 2);
  await audio.evaluate((el: HTMLAudioElement) => el.play());
  await expect.poll(() => audio.evaluate((el: HTMLAudioElement) => el.currentTime)).toBeGreaterThan(.05);
  await audio.evaluate((el: HTMLAudioElement) => el.pause());
  await page.screenshot({ path: evidence + '/preview-mobile.png', animations: 'disabled' });
  await page.setViewportSize({ width: 1440, height: 960 });
  await page.screenshot({ path: evidence + '/preview-desktop.png', animations: 'disabled' });
  const downloading = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Download audio', exact: true }).click();
  const downloaded = await downloading;
  await downloaded.saveAs(evidence + '/studio-audio.wav');
  const bytes = await readFile(evidence + '/studio-audio.wav');
  expect(bytes.toString('ascii', 0, 4)).toBe('RIFF');
  const probe = JSON.parse(execFileSync(process.env.VIRAL_HIT_FFPROBE || 'ffprobe', ['-v', 'error', '-show_format', '-show_streams', '-of', 'json', evidence + '/studio-audio.wav'], { encoding: 'utf8' }));
  expect(Number(probe.format.duration)).toBeCloseTo(1.25, 2);
  expect(probe.streams[0].codec_name).toBe('pcm_s16le');
  await expect(page.getByLabel('Saved model options').getByText('550', { exact: true })).toBeVisible();
  await page.keyboard.press('Escape');
  await page.evaluate(id => sessionStorage.removeItem(`viral-hit:studio-audio:${id}`), projectId);
  await page.reload();
  await expect(page.getByLabel('Audio prompt', { exact: true })).toHaveValue('');
  await page.locator('article').first().getByRole('button').first().click();
  await expect(page.getByLabel('Audio prompt', { exact: true })).toHaveValue('A short triangular calibration sound');
  await page.getByRole('button', { name: 'Model options', exact: true }).click();
  await expect(page.getByLabel('Wave shape', { exact: true })).toHaveValue('triangle');
  await page.keyboard.press('Escape');
  expect(requests).toHaveLength(1); expect(requests[0].mode).toBe('audio');
  expect(requests[0].parameters).toEqual({ provider_options: { frequency: 550, seconds: 1.25, wave: 'triangle' } });
  const catalog = await (await request.get(`/api/app/projects/${projectId}/assets`)).json();
  expect(catalog.assets.every((asset: { type: string }) => asset.type === 'audio')).toBe(true);
  expect(new Set(catalog.assets.map((asset: { id: string }) => asset.id)).size).toBe(1);
  expect(errors).toEqual([]);
});

test('Studio preserves unavailable audio drafts and queued generation finishes through the existing history poller', async ({ page, request }) => {
  test.setTimeout(90_000);
  const projectId = (await (await request.post('/api/app/projects', { headers, data: { name: 'Queued audio studio' } })).json()).id;
  await page.goto('/studio/' + projectId + '?target=audio&model=missing-audio-model&prompt=Keep+these+words');
  await expect(page.getByLabel('Audio model', { exact: true })).toHaveValue('missing-audio-model');
  await expect(page.getByRole('button', { name: 'Generate audio', exact: true })).toBeDisabled();
  await expect(page.getByLabel('Audio prompt', { exact: true })).toHaveValue('Keep these words');
  await page.getByLabel('Audio model', { exact: true }).selectOption('procedural-sound-queued');
  await page.getByRole('button', { name: 'Generate audio', exact: true }).click();
  await expect(page.getByText('Listen to generated audio', { exact: true })).toBeVisible({ timeout: 45_000 });
  await page.reload();
  await expect(page.getByLabel('Audio model', { exact: true })).toHaveValue('procedural-sound-queued');
  const history = (await (await request.get(`/api/app/projects/${projectId}/generations`)).json()).items;
  expect(history).toHaveLength(1); expect(history[0].status).toBe('succeeded'); expect(history[0].mediaType).toBe('audio');
  await page.evaluate(id => sessionStorage.setItem(`viral-hit:studio-audio:${id}`, '{broken'), projectId);
  await page.reload();
  await expect(page.getByText('The saved audio draft is unreadable and retained. New edits are not saved yet.', { exact: true })).toBeVisible();
  await page.getByLabel('Audio prompt', { exact: true }).fill('Recovered draft');
  expect(await page.evaluate(id => sessionStorage.getItem(`viral-hit:studio-audio:${id}`), projectId)).toBe('{broken');
  await page.getByRole('button', { name: 'Replace unreadable draft', exact: true }).click();
  await page.reload();
  await expect(page.getByLabel('Audio prompt', { exact: true })).toHaveValue('Recovered draft');
});

test('MCP discovers audio and creates an asset from a reviewed single-use request without a Canvas node', async ({ request }) => {
  async function call(name: string, args: unknown) {
    const response = await request.post('http://127.0.0.1:3043/mcp', { headers: { authorization: 'Bearer e2e-local-only', accept: 'application/json, text/event-stream' }, data: { jsonrpc: '2.0', id: 1, method: 'tools/call', params: { name, arguments: args } } });
    const text = await response.text();
    return JSON.parse(text.startsWith('{') ? text : text.split('\n').find(line => line.startsWith('data: '))!.slice(6)).result;
  }
  const models = await call('viral_hit_generation_models', { kind: 'audio' });
  expect(models.isError).not.toBe(true);
  expect(models.structuredContent.result.some((model: { id: string }) => model.id === 'procedural-sound')).toBe(true);
  const projectId = (await (await request.post('/api/app/projects', { headers, data: { name: 'MCP audio' } })).json()).id;
  const generation = { version: 2, projectId, mode: 'audio', modelId: 'procedural-sound', prompt: 'A short test tone', references: [], parameters: { provider_options: { seconds: .4 } } };
  const prepared = await call('viral_hit_asset_generation', { request: { action: 'prepare', generation } });
  expect(prepared.isError).not.toBe(true);
  const review = prepared.structuredContent.result;
  expect((await (await request.get(`/api/app/projects/${projectId}/generations`)).json()).items).toHaveLength(0);
  const submit = { action: 'submit', generation: review.generation, generationIntentToken: review.generationIntentToken, expectedDigest: review.digest };
  const result = await call('viral_hit_asset_generation', { request: submit });
  expect(result.isError).not.toBe(true); expect(result.structuredContent.result.status).toBe('succeeded');
  const inspect = { action: 'inspect', projectId, generationIntentToken: review.generationIntentToken };
  const receipt = await call('viral_hit_asset_generation', { request: inspect });
  expect(receipt.isError).not.toBe(true);
  expect(receipt.structuredContent.result.generation.id).toBe(result.structuredContent.result.wmTaskId);
  expect(receipt.structuredContent.result.generation.status).toBe('succeeded');
  expect(receipt.structuredContent.result.mayResubmit).toBe(false);
  expect(receipt.structuredContent.result.observationOnly).toBe(true);
  const foreignId = (await (await request.post('/api/app/projects', { headers, data: { name: 'Foreign receipt' } })).json()).id;
  expect((await call('viral_hit_asset_generation', { request: { ...inspect, projectId: foreignId } })).isError).toBe(true);
  const repeated = await call('viral_hit_asset_generation', { request: submit });
  expect(repeated.isError).toBe(true); expect(JSON.stringify(repeated)).toContain('already submitted');
  const history = (await (await request.get(`/api/app/projects/${projectId}/generations`)).json()).items;
  expect(history).toHaveLength(1); expect(history[0].mediaType).toBe('audio');
  const media = await request.get(history[0].resultUrl);
  expect((await media.body()).toString('ascii', 0, 4)).toBe('RIFF');
});
