import { test, expect } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import { mkdir } from 'node:fs/promises';
const headers = { 'x-viral-hit-workspace-request': '1' };
const evidence = '../../research/evidence/audio-references';
async function media() {
  await mkdir(evidence, { recursive: true });
  const audio = evidence + '/source.wav', video = evidence + '/timing.mp4';
  const ffmpeg = process.env.VIRAL_HIT_FFMPEG || 'ffmpeg';
  execFileSync(ffmpeg, ['-y', '-v', 'error', '-f', 'lavfi', '-i', 'sine=frequency=440:duration=2', '-ar', '24000', '-c:a', 'pcm_s16le', audio]);
  execFileSync(ffmpeg, ['-y', '-v', 'error', '-f', 'lavfi', '-i', 'color=c=orange:s=180x320:r=10:d=1.5', '-c:v', 'libx264', '-pix_fmt', 'yuv420p', video]);
  return { audio, video };
}

test('Studio uses audio/video references, preserves selections across model switches and reuses history without uploads', async ({ page, request }) => {
  const files = await media();
  const projectId = (await (await request.post('/api/app/projects', { headers, data: { name: 'Reference audio studio' } })).json()).id;
  const errors: string[] = [], submitted: Array<{ modelId: string; references: Array<{ assetId: string }>; parameters: unknown }> = [];
  let uploads = 0;
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', req => { if (req.method() === 'POST' && req.url().endsWith(`/projects/${projectId}/assets`)) uploads++; if (req.url().endsWith('/api/effects/generate')) submitted.push(req.postDataJSON().generation); });
  await page.goto(`/studio/${projectId}?target=audio&model=audio-conform`);
  await page.getByLabel('Audio prompt', { exact: true }).fill('Fit the soundtrack to the reference video');
  await expect(page.getByRole('button', { name: 'Generate audio', exact: true })).toBeDisabled();
  await page.getByLabel('Audio reference files', { exact: true }).setInputFiles([files.audio, files.video]);
  await expect(page.getByRole('button', { name: 'Audio sources', exact: true })).toHaveText('Sources · 2');
  expect(uploads).toBe(2);
  await page.getByRole('button', { name: 'Audio sources', exact: true }).click();
  await expect(page.getByRole('button', { name: /^Remove source source.wav/ })).toBeVisible();
  await expect(page.getByRole('button', { name: /^Remove source timing.mp4/ })).toBeVisible();
  await page.screenshot({ path: evidence + '/sources-desktop.png', animations: 'disabled' });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('button', { name: 'Done', exact: true })).toBeInViewport();
  await page.screenshot({ path: evidence + '/sources-mobile.png', animations: 'disabled' });
  await page.getByRole('button', { name: 'Done', exact: true }).click();
  await page.getByLabel('Audio model', { exact: true }).selectOption('procedural-sound');
  await expect(page.getByRole('button', { name: 'Audio sources', exact: true })).toHaveText('Sources · 2');
  await expect(page.getByRole('button', { name: 'Generate audio', exact: true })).toBeDisabled();
  await expect(page.getByText('Selected sources do not match this model.', { exact: false })).toBeVisible();
  await page.getByLabel('Audio model', { exact: true }).selectOption('audio-conform');
  await page.getByRole('button', { name: 'Model options', exact: true }).click();
  await page.getByLabel('Gain', { exact: true }).fill('.5');
  await page.getByLabel('Start in source (seconds)', { exact: true }).fill('.2');
  await page.getByLabel('Length without video (seconds)', { exact: true }).fill('.8');
  await page.getByRole('button', { name: 'Apply options', exact: true }).click();
  await page.reload();
  await expect(page.getByRole('button', { name: 'Audio sources', exact: true })).toHaveText('Sources · 2');
  await expect(page.getByRole('button', { name: 'Generate audio', exact: true })).toBeInViewport();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: evidence + '/composer-mobile.png', animations: 'disabled' });
  await page.getByRole('button', { name: 'Generate audio', exact: true }).click();
  await page.getByText('Listen to generated audio', { exact: true }).click();
  const output = page.getByLabel('Generated audio', { exact: true });
  await expect.poll(() => output.evaluate((el: HTMLAudioElement) => el.readyState)).toBeGreaterThanOrEqual(2);
  expect(await output.evaluate((el: HTMLAudioElement) => el.duration)).toBeCloseTo(1.5, 2);
  await output.evaluate((el: HTMLAudioElement) => el.play());
  await expect.poll(() => output.evaluate((el: HTMLAudioElement) => el.currentTime)).toBeGreaterThan(.05);
  await output.evaluate((el: HTMLAudioElement) => el.pause());
  await expect(page.getByLabel('Audio reference', { exact: true })).toHaveCount(1);
  await page.getByLabel('Audio reference', { exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: evidence + '/references-preview-mobile.png', animations: 'disabled' });
  await page.keyboard.press('Escape');
  await page.evaluate(id => sessionStorage.removeItem(`viral-hit:studio-audio:${id}`), projectId);
  await page.reload();
  await expect(page.getByRole('button', { name: 'Audio sources', exact: true })).toHaveText('Sources · 0');
  await page.locator('article').first().getByRole('button').first().click();
  await expect(page.getByRole('button', { name: 'Audio sources', exact: true })).toHaveText('Sources · 2');
  await page.getByRole('button', { name: 'Generate audio', exact: true }).click();
  await expect(page.getByText('Listen to generated audio', { exact: true })).toHaveCount(2);
  expect(uploads).toBe(2); expect(submitted).toHaveLength(2);
  expect(submitted[1].references.map(ref => ref.assetId).sort()).toEqual(submitted[0].references.map(ref => ref.assetId).sort());
  expect(submitted[1].parameters).toEqual(submitted[0].parameters);
  await page.getByRole('button', { name: 'Audio sources', exact: true }).click();
  await page.getByRole('button', { name: /^Remove source source.wav/ }).click();
  await page.getByRole('button', { name: 'Refresh files', exact: true }).click();
  await expect(page.getByRole('button', { name: /^Add source source.wav/ })).toHaveCount(1);
  await page.getByRole('button', { name: /^Add source source.wav/ }).click();
  await page.getByRole('button', { name: 'Done', exact: true }).click();
  expect(errors).toEqual([]);
});

test('excess audio references are rejected before uploads and a single source can be removed and added again', async ({ page, request }) => {
  const files = await media();
  const projectId = (await (await request.post('/api/app/projects', { headers, data: { name: 'Audio selection bounds' } })).json()).id;
  let uploads = 0;
  page.on('request', req => { if (req.method() === 'POST' && req.url().endsWith(`/projects/${projectId}/assets`)) uploads++; });
  await page.goto(`/studio/${projectId}?target=audio&model=audio-conform`);
  await page.getByLabel('Audio reference files', { exact: true }).setInputFiles([files.audio, files.audio]);
  await expect(page.getByText('This model allows at most 1 audio sources. Remove a source or choose another model.', { exact: true })).toBeVisible();
  expect(uploads).toBe(0);
  await page.getByLabel('Audio reference files', { exact: true }).setInputFiles([files.audio]);
  await expect(page.getByRole('button', { name: 'Audio sources', exact: true })).toHaveText('Sources · 1');
  await page.getByRole('button', { name: 'Audio sources', exact: true }).click();
  await page.getByRole('button', { name: /^Remove source source.wav/ }).click();
  await page.getByRole('button', { name: /^Add source source.wav/ }).click();
  await page.getByRole('button', { name: 'Done', exact: true }).click();
  expect(uploads).toBe(1);
});
