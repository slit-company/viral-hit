import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { seededProject } from './seeded-project';
test('an installed recognizer result previews source ranges, downloads relative SRT and remains editable after sequence attachment', async ({ page, request }) => {
  const id = await seededProject('Transcript E2E fixture'), base = `/api/app/projects/${id}`;
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(`/editor/${id}`);
  await page.getByRole('button', { name: 'Generation runs', exact: true }).click();
  await page.getByRole('combobox', { name: 'Creative recipe' }).selectOption('local-transcription-video-captions');
  const transcript = page.getByRole('region', { name: 'Speech transcript', exact: true });
  await expect(transcript).toContainText('Automatic transcript · EN');
  await expect(transcript).toContainText('protocol-fixture');
  await transcript.getByRole('button', { name: 'Preview caption 2', exact: true }).click();
  await expect.poll(() => transcript.locator('video').evaluate((video: HTMLVideoElement) => video.currentTime)).toBe(1.1);
  await transcript.locator('video').evaluate((video: HTMLVideoElement) => { video.currentTime = 1.5; });
  await transcript.getByRole('button', { name: 'Preview caption 2', exact: true }).click();
  await expect.poll(() => transcript.locator('video').evaluate((video: HTMLVideoElement) => video.currentTime)).toBe(1.1);
  const download = page.waitForEvent('download');
  await transcript.getByRole('button', { name: 'Download SRT', exact: true }).click();
  const srt = await download, path = await srt.path();
  expect(await readFile(path!, 'utf8')).toBe('1\n00:00:00,000 --> 00:00:00,800\nFixture speech\n\n2\n00:00:01,100 --> 00:00:01,800\nEditable captions\n');
  await page.setViewportSize({ width: 390, height: 844 });
  await transcript.scrollIntoViewIfNeeded();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await expect(transcript.getByRole('button', { name: 'Download SRT', exact: true })).toBeVisible();
  const accepted = page.waitForResponse(response => response.url().endsWith(base + '/runs') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Add editable sequence', exact: true }).click();
  expect((await (await accepted).json()).ok).toBe(true);
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  await page.setViewportSize({ width: 1440, height: 960 });
  await page.getByRole('button', { name: 'Fixture speech 0.80s', exact: true }).click();
  await page.locator('textarea').first().fill('Reviewed caption');
  const read = async () => (await (await request.get(base + '/timeline')).json()).timeline;
  await expect.poll(async () => (await read()).document.tracks.flatMap((track: { clips: { text?: string }[] }) => track.clips).some((clip: { text?: string }) => clip.text === 'Reviewed caption')).toBe(true);
  await page.reload(); await expect(page.getByRole('button', { name: 'Reviewed caption 0.80s', exact: true })).toBeVisible();
  const timeline = await read();
  expect(timeline.document.tracks.flatMap((track: { clips: { sourceType: string }[] }) => track.clips).filter((clip: { sourceType: string }) => clip.sourceType === 'caption')).toHaveLength(2);
  const runs = (await (await request.get(base + '/runs')).json()).runs;
  expect(JSON.parse(runs[0].jobs.find((job: { operation: string }) => job.operation === 'ext.whisper-transcribe').output_json).transcript.segments[0].text).toBe('Fixture speech');
  expect(errors).toEqual([]);
});
