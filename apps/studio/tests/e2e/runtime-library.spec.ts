import { test, expect, type APIRequestContext } from '@playwright/test';
import { createHash } from 'node:crypto';
import { readFile, mkdir } from 'node:fs/promises';
const endpoint = '/api/app/runtime-packages', headers = { 'x-viral-hit-workspace-request': '1' };
async function post(request: APIRequestContext, body: unknown) {
  const response = await request.post(endpoint, { headers, data: body });
  expect(response.ok(), await response.text()).toBe(true);
  return response.json();
}
async function replace(request: APIRequestContext, pkg: unknown) {
  const review = await post(request, { action: 'inspect', package: pkg });
  await post(request, { action: 'apply', package: review.package, expectedDigest: review.digest, expectedStateDigest: review.stateDigest, trustCode: true });
}

