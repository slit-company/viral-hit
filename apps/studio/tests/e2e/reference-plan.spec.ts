import { test, expect } from '@playwright/test';
import { seededProject } from './seeded-project';

test('a completed scene and independent speech result become a reviewed portable storyboard draft without automatic production', async ({ page, request }) => {
  const id = await seededProject('Reference plan E2E fixture'), base = '/api/app/projects/' + id;
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/storyboards/' + id);
  await expect(page.getByRole('button', { name: 'New storyboard', exact: true })).toBeEnabled();
  await page.getByText('Start from analyzed video', { exact: true }).click();
  const sources = await (await request.post(base + '/storyboards', { headers: { 'x-viral-hit-workspace-request': '1' }, data: { action: 'reference-sources' } })).json();
  const scene = sources.sources.find((item: { kind: string }) => item.kind === 'scenes'), speech = sources.sources.find((item: { kind: string }) => item.kind === 'transcript');
  await page.getByLabel('Analyzed video', { exact: true }).selectOption(scene.jobId);
  await page.getByLabel('Speech context', { exact: true }).selectOption(speech.jobId);
  await page.getByLabel('Reference plan use case', { exact: true }).selectOption('specialized');
  await page.getByLabel('Reference plan intent', { exact: true }).fill('Make an instructional clip from this source timing.');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Prepare reference draft', exact: true }).scrollIntoViewIfNeeded();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Prepare reference draft', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Creative intent', exact: true })).toHaveValue('Make an instructional clip from this source timing.');
  await expect(page.getByLabel('Use case', { exact: true })).toHaveValue('specialized');
  const references = page.getByRole('region', { name: 'Reference observations', exact: true });
  await expect(references).toContainText('Machine-estimated speech');
  await expect(references).toContainText('protocol-fixture');
  await expect(page.getByLabel('Observation basis 1', { exact: true })).toHaveValue('inferred');
  await expect(page.getByRole('button', { name: 'Prepare reference draft', exact: true })).toHaveCount(0);
  await page.getByText('Start from analyzed video', { exact: true }).click();
  await expect(page.getByRole('button', { name: 'Prepare reference draft', exact: true })).toBeDisabled();
  await page.getByText('Start from analyzed video', { exact: true }).click();
  expect(await (await request.get(base + '/storyboards')).json()).toEqual([]);
  const before = (await (await request.get(base + '/runs')).json()).runs.length;
  await page.getByRole('button', { name: 'Save plan', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Saved revision 1.' })).toBeVisible();
  const boards = await (await request.get(base + '/storyboards')).json();
  const board = await (await request.post(base + '/storyboards', { headers: { 'x-viral-hit-workspace-request': '1' }, data: { action: 'read', id: boards[0].id } })).json();
  expect(board.accepted).toEqual({}); expect(board.actions).toEqual([]);
  expect(board.plan.references.every((ref: { evidence?: { outputSha256: string } }) => ref.evidence?.outputSha256)).toBe(true);
  expect((await (await request.get(base + '/runs')).json()).runs).toHaveLength(before);
  await page.reload();
  await page.getByRole('button', { name: 'Plan & references', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Creative intent', exact: true })).toHaveValue('Make an instructional clip from this source timing.');
  expect(errors).toEqual([]);
});
